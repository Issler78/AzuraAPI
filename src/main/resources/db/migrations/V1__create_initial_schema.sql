CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT pk_categories PRIMARY KEY,
    deleted_at TIMESTAMP(6),
    name VARCHAR(100) NOT NULL
        CONSTRAINT uk_categories_name UNIQUE
);

CREATE TABLE courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT pk_courses PRIMARY KEY,
    category_id BIGINT NOT NULL
        CONSTRAINT fk_courses_category
        REFERENCES categories (id),
    deleted_at TIMESTAMP(6),
    description TEXT NOT NULL,
    title VARCHAR(255) NOT NULL
        CONSTRAINT uk_courses_title UNIQUE,
    price NUMERIC(10, 2) NOT NULL
);

CREATE TABLE roles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT pk_roles PRIMARY KEY,
    name VARCHAR(255) NOT NULL
        CONSTRAINT uk_roles_name UNIQUE
);

CREATE TABLE users (
    id UUID NOT NULL
        CONSTRAINT pk_users PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    cpf CHAR(11) NOT NULL
        CONSTRAINT uk_users_cpf UNIQUE,
    email VARCHAR(255) NOT NULL
        CONSTRAINT uk_users_email UNIQUE,
    password VARCHAR(255) NOT NULL
);

CREATE TABLE enrollments (
    id UUID NOT NULL
        CONSTRAINT pk_enrollments PRIMARY KEY,
    certificate_issued BOOLEAN NOT NULL,
    completion_date DATE,
    completion_percentage INTEGER NOT NULL,
    enrollment_date DATE NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    course_id BIGINT NOT NULL
        CONSTRAINT fk_enrollments_course
        REFERENCES courses (id),
    status_updated_at TIMESTAMP(6),
    user_id UUID NOT NULL
        CONSTRAINT fk_enrollments_user
        REFERENCES users (id),
    status VARCHAR(255) NOT NULL
        CONSTRAINT ck_enrollments_status
        CHECK (
            status IN (
                'PENDING_PAYMENT',
                'ACTIVE',
                'CANCELED',
                'COMPLETED',
                'ON_LEAVE'
            )
        )
);

CREATE TABLE users_roles (
    role_id INTEGER NOT NULL
        CONSTRAINT fk_users_roles_role
        REFERENCES roles (id),
    user_id UUID NOT NULL
        CONSTRAINT fk_users_roles_user
        REFERENCES users (id),
    CONSTRAINT pk_users_roles
        PRIMARY KEY (role_id, user_id)
);

CREATE TABLE payments (
    id UUID NOT NULL
        CONSTRAINT pk_payments PRIMARY KEY,
    amount NUMERIC(10, 2) NOT NULL,
    gateway_payment_id UUID
        CONSTRAINT uk_payments_gateway_payment_id UNIQUE,
    paid_at TIMESTAMP(6),
    payment_method VARCHAR(255) NOT NULL
        CONSTRAINT ck_payments_payment_method
        CHECK (
            payment_method IN (
                'PIX',
                'CREDIT_CARD',
                'DEBIT_CARD'
            )
        ),
    status VARCHAR(255) NOT NULL
        CONSTRAINT ck_payments_status
        CHECK (
            status IN (
                'PENDING',
                'ACCEPTED',
                'REJECTED',
                'FAILED'
            )
        ),
    enrollment_id UUID NOT NULL
        CONSTRAINT uk_payments_enrollment_id UNIQUE
        CONSTRAINT fk_payments_enrollment
        REFERENCES enrollments (id),
    failure_reason VARCHAR(255)
);